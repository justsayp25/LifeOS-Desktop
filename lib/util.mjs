// Small shared helpers for the vault modules.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { vp, rel, exists, readNote, writeNote, todayStr, isDate, setFrontmatter, getFrontmatter, fillTemplate, HttpError, VAULT } from './vault.mjs';

export const MARKER = '<!-- AUTO-GENERATED by hub.py';
export const b64 = (s) => Buffer.from(s, 'utf8').toString('base64url');
export const unb64 = (s) => Buffer.from(s, 'base64url').toString('utf8');
export const h8 = (s) => crypto.createHash('sha1').update(s).digest('hex').slice(0, 8);
export const markerIndex = (lines) => { const i = lines.findIndex((l) => l.startsWith(MARKER)); return i < 0 ? lines.length : i; };

// Named "## " section limited to hand-written space (never past the hub marker). Returns [headingIdx, endIdx] or null.
export function section(lines, re) {
  const lim = markerIndex(lines);
  const s = lines.findIndex((l, i) => i < lim && /^##\s/.test(l) && re.test(l));
  if (s < 0) return null;
  let e = lim;
  for (let i = s + 1; i < lim; i++) if (/^##\s/.test(lines[i])) { e = i; break; }
  return [s, e];
}
export const walkMd = (dir, out = [], depth = 0) => {
  if (depth > 6 || !exists(dir)) return out;
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    if (f.name.startsWith('.')) continue;
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walkMd(p, out, depth + 1);
    else if (f.name.endsWith('.md')) out.push(p);
  }
  return out;
};
export const touch = (text) => setFrontmatter(text, 'updated', todayStr());

// Insert bullet lines after the last bullet of a section (or right after its heading), never below the hub marker.
export function insertInSection(lines, sec, newLines) {
  let at = sec[0] + 1;
  for (let i = sec[0] + 1; i < sec[1]; i++) if (/^\s*[-*]\s/.test(lines[i]) || /^###\s/.test(lines[i])) at = i + 1;
  lines.splice(at, 0, ...newLines);
}

export function dailyPath(date) { return vp('1 Human', '02 Daily', date.slice(0, 7), date + '.md'); }
export function ensureDaily(date) {
  const p = dailyPath(date);
  if (exists(p)) return p;
  const tpl = vp('2 Machine', '01 Templates', 'Daily.md');
  if (!exists(tpl)) throw new HttpError(500, 'The Daily template is missing.');
  const { text, eol } = readNote(tpl);
  writeNote(p, fillTemplate(text, { date, title: date }), eol);
  return p;
}
export function ensureFromTemplate(abs, tplName, title, date = todayStr()) {
  const tpl = vp('2 Machine', '01 Templates', ...tplName.split('/'));
  if (!exists(tpl)) throw new HttpError(500, `The ${tplName} template is missing.`);
  const { text, eol } = readNote(tpl);
  // Templater code blocks (<%* ... %>) are for Obsidian only.
  const clean = text.replace(/<%\*[\s\S]*?%>\r?\n?/g, '');
  writeNote(abs, fillTemplate(clean, { date, title }), eol);
}
export function bin(abs) {
  const dest0 = vp('1 Human', '99 Bin', path.basename(abs));
  let dest = dest0, n = 2;
  while (exists(dest)) { dest = dest0.replace(/\.md$/, ` (${n++}).md`); }
  const { text, eol } = readNote(abs);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.renameSync(abs, dest);
  let t = text.replace(/^connections:.*(?:\n[ \t]+-.*)*$/m, 'connections: []');
  t = touch(t);
  writeNote(dest, t, eol);
  return rel(dest);
}
export const cleanName = (s) => String(s || '').replace(/[\\/:*?"<>|#^\[\]]/g, ' ').replace(/\s+/g, ' ').trim().replace(/^[.\s]+/, '').replace(/[.\s]+$/, '');
